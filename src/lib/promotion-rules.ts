export function promotionStep(name:string){
 const normalized=name.trim().toLocaleLowerCase('uk').replace(/[‐‑–—]/g,'-');
 return promotionLadder.find(([from])=>from.toLocaleLowerCase('uk')===normalized||
  (from==='Рядовий'&&normalized==='солдат'));
}

export function promotionRankName(id:number,name:string){
 return name.trim()===String(id)?(promotionLadder[id-1]?.[0]??(id===10?promotionLadder[8][1]:name)):name;
}
